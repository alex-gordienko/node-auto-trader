"""Builds report.md from results.parquet / trades.parquet / ob_results.json (run study.py and ob.py first)."""
import json, os, sys
import numpy as np, pandas as pd

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from data import load
from study import COSTS, HORIZONS, TREND_LOOKBACKS, TEST_YEARS

HERE = os.path.dirname(os.path.abspath(__file__))
R = pd.read_parquet(os.path.join(HERE, "results.parquet"))
T = pd.read_parquet(os.path.join(HERE, "trades.parquet"))
H_ORDER = list(HORIZONS)


def daily_baselines(sym):
    d = load(sym)
    c = pd.Series(d["c"].values, pd.to_datetime(d["t"].values + 60_000, unit="ms"))
    px = c[c.index.hour.isin([0]) & (c.index.minute == 0)]
    px.index = px.index.normalize()
    vote = sum((px > px.shift(k)).astype(float) for k in TREND_LOOKBACKS) / len(TREND_LOOKBACKS)
    out = {}
    for name, w in (("Buy & hold", pd.Series(1.0, px.index)), ("Trend vote 10–120d", vote)):
        w = w.shift(1).fillna(0)
        r = w * px.pct_change() - w.diff().abs().fillna(0) * 0.0012  # 0.1% taker + 0.02% slippage per unit traded
        r = r[r.index >= f"{TEST_YEARS[0]}-01-01"]
        eq = (1 + r).cumprod()
        yrs = len(r) / 365
        out[name] = dict(ann=eq.iloc[-1] ** (1 / yrs) - 1, sharpe=r.mean() / r.std() * np.sqrt(365), mdd=(eq / eq.cummax() - 1).min())
    return out


def f(v, p=1, pct=False):
    if v is None or (isinstance(v, float) and np.isnan(v)):
        return "–"
    return f"{v*100:+.{p}f}%" if pct else f"{v:+.{p}f}"


def main():
    L = ["# Best prediction window with at most 3 entries a day — BTC / ETH (Binance spot)", "",
         f"Generated by `study.py` / `ob.py` / `report.py` on {pd.Timestamp.now('UTC'):%Y-%m-%d}.", "",
         "## Setup", "",
         "- **Data:** Binance spot 1-minute klines 2020-01 … 2026-10-23, with taker buy volume. Daily context comes from the same "
         "data plus Binance funding (3-day mean). The other coin's returns are included.",
         "- **Features (30, all causal):** returns over 1 m … 3 d; realized vol 1 h / 1 d; volume ratios; taker imbalance 5 m / 1 h / 4 h; "
         "1 h and 5 m range; distance from the 24 h VWAP, high and low; hour and weekday; trend vote 10–120 d; 30 d return; funding.",
         "- **Decisions** every 5 minutes. **Horizons:** 5 m, 15 m, 1 h, 4 h, 12 h, 1 d, 3 d.",
         "- **Models:** gradient-boosted trees (sklearn HistGradientBoosting) and ridge. Walk-forward: each test year 2022 … 2026 is "
         "predicted by a model trained on all data before it, with labels ending before the year starts.",
         "- **Selection — the 3-a-day rule:**",
         "  - Trade when the score is beyond the quantile 1 − 3/288 of the previous 30 days' scores (a causal threshold).",
         "  - At most 3 entries per UTC day, one position at a time, held exactly the horizon.",
         "  - `long` = spot long/flat. `ls` = long or short (needs perp or margin).",
         "- **Costs** are per round trip and include 0.02 % slippage per side:",
         "  - maker 0.02 % → 8 bps; maker 0.05 % → 14 bps; taker 0.1 % → 24 bps.",
         "  - The bot's current 0.7 % per swap → 140 bps.",
         "- **Controls:**",
         "  - `random`: 3 random entries a day, same holding rules. It shows the market drift.",
         "  - `oracle`: perfect foresight, the 3 best non-overlapping entries of each day. It is the upper bound before costs.",
         "- Test period 2022-01-01 → 2026-10-23 (≈4.8 years). Sharpe is computed on daily PnL × √365. t = t-stat of the mean net return "
         "per trade (trades do not overlap).", ""]
    for sym in ("BTCUSDT", "ETHUSDT"):
        b = daily_baselines(sym)
        L += [f"## {sym}", "",
              "Baselines 2022 → now, daily, 0.12 % per unit traded: " + "; ".join(f"**{k}** {v['ann']*100:+.1f}%/yr, Sharpe {v['sharpe']:.2f}, max DD {v['mdd']*100:.0f}%" for k, v in b.items()) + ".", "",
              "### Edge before costs", "",
              "IC = Spearman correlation of the score with the realized return over all decision points. The other columns are the average gross "
              "return per selected trade in bps, with trades/day in brackets.", "",
              "| Horizon | mode | IC gbm | IC ridge | gbm bps | ridge bps | random bps | oracle bps |", "|---|---|---|---|---|---|---|---|"]
        for h in H_ORDER:
            for mode in ("long", "ls"):
                g = R[(R.sym == sym) & (R.h == h) & (R["mode"] == mode) & (R.cost == "gross")].set_index("model")
                cell = lambda m: f"{g.loc[m, 'net_bps']:+.1f} ({g.loc[m, 'trades_day']:.1f})"
                L.append(f"| {h} | {mode} | {g.loc['gbm', 'ic']:+.3f} | {g.loc['ridge', 'ic']:+.3f} | {cell('gbm')} | {cell('ridge')} | {cell('random')} | {cell('oracle')} |")
        L += ["", "### After costs (gbm / ridge)", "",
              "| Horizon | mode | model | trades/day | hit (8 bps) | net bps @8 | @14 | @24 | @140 | ann. @8 | ann. @24 | Sharpe @8 | Sharpe @24 | maxDD @24 | t @24 |",
              "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
        for h in H_ORDER:
            for mode in ("long", "ls"):
                for m in ("gbm", "ridge"):
                    g = R[(R.sym == sym) & (R.h == h) & (R["mode"] == mode) & (R.model == m)].set_index("cost")
                    a, b8, b14, b24, b140 = (g.loc[c] for c in ("gross", "maker 0.02%", "maker 0.05%", "taker 0.1%", "bot 0.7%"))
                    L.append(f"| {h} | {mode} | {m} | {a.trades_day:.2f} | {b8.hit:.2f} | {b8.net_bps:+.1f} | {b14.net_bps:+.1f} | {b24.net_bps:+.1f} | {b140.net_bps:+.0f} | "
                             f"{b8.ann*100:+.1f}% | {b24.ann*100:+.1f}% | {b8.sharpe:.2f} | {b24.sharpe:.2f} | {b24.mdd*100:.0f}% | {b24.t:+.2f} |")
        L.append("")
        # per-year stability of the gross edge for every horizon (gbm, long and ls)
        L += ["### Gross bps per trade by year (gbm)", "", "| Horizon | mode | " + " | ".join(str(y) for y in TEST_YEARS) + " |", "|---|---|" + "---|" * len(TEST_YEARS)]
        for h in H_ORDER:
            for mode in ("long", "ls"):
                t = T[(T.sym == sym) & (T.h == h) & (T["mode"] == mode) & (T.model == "gbm")]
                by = t.groupby(pd.to_datetime(t.t).dt.year)["gross"].agg(["mean", "size"])
                L.append(f"| {h} | {mode} | " + " | ".join(f"{by.loc[y, 'mean']*1e4:+.1f} ({by.loc[y, 'size']})" if y in by.index else "–" for y in TEST_YEARS) + " |")
        L.append("")
    ob = json.load(open(os.path.join(HERE, "ob_results.json")))
    L += ["## Recorded order books (bot's collectors, futures top-20 book each second)", "",
          "Trained on the first ~60 % of the recorded days and tested on the rest. The model is gradient-boosted trees on book imbalance (levels 1/5/20), "
          "microprice, spread, and 10 s–5 m mid returns and volatility. Long or short, ≤3 entries/day, with the threshold taken from the training days. **A tiny sample: "
          "a few days and a dozen trades. Indicative only.**", "",
          "| Symbol | horizon | test days | IC | trades | gross bps/trade | net @8 | net @24 | oracle bps | median abs move bps |", "|---|---|---|---|---|---|---|---|---|---|"]
    for sym, r in ob.items():
        for h in ("10s", "60s", "300s"):
            x = r[h]
            L.append(f"| {sym} | {h} | {r['test_days']} | {x['ic']:+.3f} | {x['trades']} | {f(x['gross_bps'])} | {f(x['net_bps']['maker 0.02%'])} | {f(x['net_bps']['taker 0.1%'])} | {x['oracle_gross_bps']:.1f} | {x['median_abs_move_bps']:.2f} |")
    open(os.path.join(HERE, "report.md"), "w").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
